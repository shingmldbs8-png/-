def is_numeric(choices) -> bool:
    return all(c[:1].isdigit() or c[:1] in "φ−-" for c in choices)


def balance() -> None:
    """수치형이 아닌 문항은 정답 위치를 덜 쓰인 번호로 옮겨 ①~④ 분포를 고르게 한다."""
    count = {k: 0 for k in range(1, 5)}
    for _, items in SUBJECTS:
        for i, (q, choices, ans, exp) in enumerate(items):
            if not is_numeric(choices):
                target = min(count, key=lambda k: (count[k], k))
                choices = list(choices)
                choices[ans - 1], choices[target - 1] = choices[target - 1], choices[ans - 1]
                ans = target
                items[i] = (q, choices, ans, exp)
            count[ans] += 1


