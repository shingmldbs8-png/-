const run = (text, o = {}) => new TextRun({ text, bold: o.bold, size: o.size ?? 20, color: o.color });
const P = (text, o = {}) => new Paragraph({
  spacing: { before: o.before ?? 0, after: o.after ?? 60 },
  indent: o.indent ? { left: o.indent } : undefined,
  alignment: o.align, keepNext: o.keepNext,
  children: Array.isArray(text) ? text : [run(text, o)],
});
const shade = (fill) => ({ type: ShadingType.CLEAR, fill, color: 'auto' });

function T(header, rows, opt = {}) {
  const n = header.length;
  const widths = opt.widths ?? Array(n).fill(Math.floor(W / n));
  const total = widths.reduce((a, b) => a + b, 0);
  const mk = (txt, i, head) => new TableCell({
    width: { size: widths[i], type: WidthType.DXA },
    shading: head ? shade('E8EEF7') : undefined,
    margins: { top: 40, bottom: 40, left: 80, right: 80 },
    children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [run(String(txt), { size: 18, bold: head })] })],
  });
  return new Table({
    width: { size: total, type: WidthType.DXA }, columnWidths: widths,
    rows: [new TableRow({ tableHeader: true, children: header.map((h, i) => mk(h, i, true)) }),
      ...rows.map((r) => new TableRow({ children: r.map((c, i) => mk(c, i, false)) }))],
  });
}

// 답안 칸: [계산과정] + [답]
function answerBox(lines = 5) {
  const cell = (label, h) => new TableRow({
    height: { value: h, rule: HeightRule.ATLEAST },
    children: [new TableCell({ width: { size: W, type: WidthType.DXA },
      children: [new Paragraph({ children: [run(label, { size: 17, color: '666666' })] })] })],
  });
  return new Table({ width: { size: W, type: WidthType.DXA }, columnWidths: [W],
    rows: [cell('[계산과정]', 320 * lines), cell('[답]', 520)] });
}

const space = () => new Paragraph({ spacing: { after: 120 }, children: [] });

// 정답 + 단계 풀이 (시험지 뒤 해설 페이지와 공부용 버전에서 같이 사용)
function solution(q, no) {
  const out = [P([run('정답  ', { bold: true, size: 19 }), run(q.ans, { size: 19, color: BLUE, bold: true })], { indent: 200 })];
  q.sol.forEach((s) => {
    if (typeof s === 'string') out.push(P(s, { indent: s.startsWith('·') ? 400 : 200, size: 18, after: 30, bold: /^(\d단계|핵심|자주)/.test(s), before: /^\d단계/.test(s) ? 60 : 0 }));
    else { out.push(T(s.t, s.r, { widths: s.w })); out.push(new Paragraph({ spacing: { after: 40 }, children: [] })); }
  });
  (SOLFIG[no] || []).forEach((n) => out.push(...figure(n, 520)));
  return out;
}


